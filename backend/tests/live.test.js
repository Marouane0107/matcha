const clients = [];
const connect = async token => {
  const socket = connectSocket(base, { auth: { accessToken: token }, autoConnect: false, reconnection: false });
  clients.push(socket);
  const connected = new Promise((resolve, reject) => { socket.once('connect', () => resolve(socket)); socket.once('connect_error', reject); });
  socket.connect(); return connected;
};
const ack = (socket, event, payload) => new Promise((resolve, reject) => socket.timeout(3000).emit(event, payload, (error, response) => error ? reject(error) : resolve(response)));
const nextEvent = (socket, event) => new Promise((resolve, reject) => {
  const timer = setTimeout(() => { socket.off(event, received); reject(Error(`Missing ${event}`)); }, 3000);
  function received(value) { clearTimeout(timer); resolve(value); }
  socket.once(event, received);
});
async function request(path, method = 'GET', body, token) {
  const response = await fetch(base + path, { method, headers: { ...(body ? { 'Content-Type': 'application/json' } : {}), ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body ? JSON.stringify(body) : undefined });
  return { status: response.status, body: response.status === 204 ? null : await response.json() };
}
